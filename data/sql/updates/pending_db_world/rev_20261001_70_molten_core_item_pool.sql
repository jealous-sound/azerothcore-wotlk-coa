-- Molten Core random item pool: on every scheduled boss kill (the 8 T1-token bosses,
-- Majordomo Executus and Ragnaros -- creature loot only, Majordomo's Cache of the Firelord
-- chest excluded for now), the kill drops N random items in addition to the guaranteed set
-- tokens, where N follows the same flex raid-size band FlexHealth.cpp/FlexLoot.cpp already use
-- (coa_flex::CountPlayers, clamped 10..25): 10-14 players -> 2 items, 15-19 -> 3, 20-25 -> 4.
--
-- The pool for each kill is the union of that boss's own items (items that only ever dropped
-- from that boss's table) and a pool common to every boss (items this fork's own
-- creature_loot_template already shared across more than one boss's table before this change).
-- Re-reading the 9 scheduled bosses' Normal creature_loot_template shows no single item was
-- shared across literally every boss -- the real sharing is four boss pairs, each pair sharing
-- one family of items (Golemagg/Baron Geddon, Magmadar/Garr, Sulfuron Harbinger/Shazzrah,
-- Lucifron/Gehennas); this migration promotes each pair's shared family into one global common
-- pool available to every boss's draw, and keeps each boss's own leftover items (plus all of
-- Ragnaros's own 15-item pool, which shares with no one) as that boss's own pool. Majordomo
-- Executus carries no creature_loot_template rows of his own at all (his loot is the Cache of
-- the Firelord gameobject, out of this migration's scope) and so draws only from the common
-- pool. Every item in both pools is class 2 (Weapon) or 4 (Armor), quality 4 (epic) -- confirmed
-- against item_template -- matching the "non-set epic gear" rows this fix moves, not set tokens,
-- currency, legendaries, quest items or the case/pack groups (left untouched at their existing
-- chances).
--
-- Weights mirror the export: every item within a given boss's own gear group already rolled at
-- an identical per-item chance (0.154-0.571% depending on the group), so a uniform weight of 1
-- for every row preserves those ratios exactly -- there is no item in either pool that the
-- export weighted more or less than its group-mates.
--
-- Per-difficulty item ids follow the same id convention rev_20261001_41 already established and
-- used to restore these exact rows on scaled bosses: Heroic = Normal id + 300000, Mythic =
-- Normal id + 1300000, Ascended = Normal id + 200000.
--
-- The old per-group tiny-chance rolls that these items came from (Normal GroupId 2/3/4 on the
-- base entries, GroupId 10/11 on the Heroic/Mythic/Ascended entries added by rev_20261001_41) are
-- deleted below so nothing can drop twice -- once from the old per-item roll and once from the
-- new weighted pool draw. The CoA case/pack group (GroupId 37) and every guaranteed/currency row
-- (GroupId 0, 1, 5-9) are untouched.

