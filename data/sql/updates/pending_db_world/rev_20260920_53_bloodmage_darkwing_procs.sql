(500012, 1, 0, 0, 0, 0, 60, 1, 2, 0, 0, 0, 0, 0, 0, 0),
(300260, 0, 26, 0, 268435456, 0, 5120, 0, 6, 0, 2, 0, 0, 0, 1000, 0);
