-- docs/coa/molten-core.md SS7.1). This migration repoints those same reference ids, already
-- wired to FlexLoot's guaranteed 2-pick (3 at 20+ players) roll, at the real Molten token set
-- for their difficulty, shared across all nine scheduled bosses (matching "a pool of MC T1
-- tokens", not one fixed slot per boss) so every guaranteed pick is now an actual, recognizable
-- Tier 1 token. No C++ change is needed: FlexLoot.cpp and coa_mc_token_loot already read
-- reference_loot_template by id, data-driven.
--
-- The export's own single low-chance "Molten <slot>" row already present directly in each
-- boss's own creature_loot_template (e.g. 2522362 at 2% on Lucifron, group 3, mutually
-- exclusive with the guaranteed Rune of Descension in the same group) is left untouched: an
-- export-authored bonus roll on top of the now-guaranteed pool pick, not a duplicate of it.
--
-- T2 (Chromatic <Slot>) is not touched the same way: of the nine scheduled MC bosses, only
-- Ragnaros drops one (Chromatic Legguards, the Tier 2 Leg token) at the export's own low
-- chance (4%, group 5) -- every other Chromatic-token-bearing creature in the export
-- (Onyxia, Nefarian, Firemaw, Broodlord Lashlayer, Vaelastrasz, Chromaggus) belongs to a
-- different raid, out of this fix's scope. Ragnaros's own row has a real, separate bug: the
-- Mythic and Ascended creature_loot_template rows swapped their tier-specific item ids
-- (Mythic entry 211502 carried the Ascended id 3722459, and Ascended entry 311502 carried the
