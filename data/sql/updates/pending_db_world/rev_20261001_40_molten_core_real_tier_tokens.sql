-- live client captures in the AscensionDB mirror (records tagged source "Client captures",
-- modes including "conquest-of-azeroth"/"season-9"/"season-10-freepick"): the class-15
-- (Misc), subclass-0 (Junk), quality-4 (epic), non-equip, reqlvl-60 "Molten <Slot>" items
-- (Tunic/Legguards/Headpiece/Spaulders/Wristguards/Girdle/Handguards/Boots), one per
-- difficulty tier (2522xxx Normal/2622xxx Heroic/2722xxx Mythic/3722xxx Ascended). Their own
-- in-game tooltip, captured verbatim, says so directly:
--   "This Token is a Global Token for Tier 1 <Slot> Slot items. This is Exchangeable at a
--   Vendor found in Stormwind (Major Mattingly) or Orgrimmar (Overlord Runthak)."
-- The "Chromatic <Slot>" family is the same system for Tier 2 (BWL), same two vendors,
-- confirmed the same way. Major Mattingly (14394) and Overlord Runthak (14392) already exist
-- in creature_template with the gossip+vendor npcflag (3) but an empty npc_vendor list: the
-- token-for-gear exchange itself is unimplemented and out of scope for this fix (it needs its
-- own item_extended_cost/npc_vendor design per slot/class, not invented here).
--
-- rev_20260930_80 (gen_mc_loot_fix.py) built the FlexLoot-guaranteed "Tier 1 reference pool"
-- (reference_loot_template 4090011-4090057, wired per rev_20261001_12_molten_core_token_loot
-- through FlexLoot.cpp) from the export's classic per-class Tier 1 armor pieces (Felheart
-- Gloves 16805, Sorcerous Dagger 18878, ...) instead: real items, but not tokens, and not
-- generally recognizable as a reward tied to Molten Core, which is the root cause of "no T1
